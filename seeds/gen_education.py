#!/usr/bin/env python3
"""Generates seeds/003_education.sql from seeds/education/course*.py and glossary.py. Idempotent.

- Course 1 reuses the existing 'Introduction to Ethiopian Capital Markets' course/lessons so existing learner progress stays valid.
- Placeholder content (the 8-hour 'Capital Markets' stub course and the 'Equities' / 'Next' lessons) is soft-deleted.
- Each lesson ends up with exactly ONE quiz (the app fetches the first quiz per lesson).
"""
import json, sys
sys.path.insert(0, ".")
from education import course1, course2, course3, course4, course5, course6, glossary

def q(s): return "$q$" + s + "$q$"

courses = [course1, course2, course3, course4, course5, course6]
out = ["-- Generated by seeds/gen_education.py. Idempotent.", "BEGIN;"]

out.append("""
CREATE OR REPLACE FUNCTION pg_temp.seed_lesson(p_course uuid, p_existing_title text, p_title text, p_content text, p_video text, p_order int, p_questions jsonb)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE v_lesson uuid; v_quiz uuid; v_q jsonb;
BEGIN
  SELECT id INTO v_lesson FROM lessons WHERE course_id = p_course AND deleted_at IS NULL AND title IN (COALESCE(p_existing_title, p_title), p_title) ORDER BY (title = COALESCE(p_existing_title, p_title)) DESC LIMIT 1;
  IF v_lesson IS NULL THEN
    INSERT INTO lessons (course_id, title, content, "order", video_url, created_at, updated_at)
    VALUES (p_course, p_title, p_content, p_order, COALESCE(p_video, ''), now(), now()) RETURNING id INTO v_lesson;
  ELSE
    UPDATE lessons SET title = p_title, content = p_content, "order" = p_order, video_url = COALESCE(p_video, ''), updated_at = now() WHERE id = v_lesson;
  END IF;

  -- keep one quiz (prefer one referenced by a submission), drop the rest
  SELECT z.id INTO v_quiz FROM quizzes z WHERE z.lesson_id = v_lesson
    ORDER BY (EXISTS (SELECT 1 FROM quiz_submissions s WHERE s.quiz_id = z.id)) DESC, z.created_at ASC LIMIT 1;
  IF v_quiz IS NULL THEN
    INSERT INTO quizzes (lesson_id, created_at, updated_at) VALUES (v_lesson, now(), now()) RETURNING id INTO v_quiz;
  ELSE
    DELETE FROM questions WHERE quiz_id IN (SELECT id FROM quizzes WHERE lesson_id = v_lesson AND id <> v_quiz);
    DELETE FROM quizzes WHERE lesson_id = v_lesson AND id <> v_quiz
      AND NOT EXISTS (SELECT 1 FROM quiz_submissions s WHERE s.quiz_id = quizzes.id);
    DELETE FROM questions WHERE quiz_id = v_quiz;
  END IF;
  FOR v_q IN SELECT * FROM jsonb_array_elements(p_questions) LOOP
    INSERT INTO questions (quiz_id, question, options, correct) VALUES (v_quiz, v_q->>'q', v_q->'options', (v_q->>'correct')::int);
  END LOOP;
END
$fn$;
""")

# retire placeholder content
out.append("UPDATE courses SET deleted_at = now() WHERE title = 'Capital Markets' AND deleted_at IS NULL;")
out.append("UPDATE lessons SET deleted_at = now() WHERE title IN ('Equities','Next') AND deleted_at IS NULL;")

for idx, mod in enumerate(courses):
    c = mod.COURSE
    if c.get("existing_id"):
        out.append(f"UPDATE courses SET title={q(c['title'])}, duration={q(c['duration'])}, description={q(c['description'])}, updated_at=now(), deleted_at=NULL WHERE id='{c['existing_id']}';")
    else:
        out.append(f"""INSERT INTO courses (title, description, duration, created_at, updated_at)
SELECT {q(c['title'])}, {q(c['description'])}, {q(c['duration'])}, now() + interval '{idx} seconds', now()
WHERE NOT EXISTS (SELECT 1 FROM courses WHERE title={q(c['title'])} AND deleted_at IS NULL);
UPDATE courses SET description={q(c['description'])}, duration={q(c['duration'])}, updated_at=now() WHERE title={q(c['title'])} AND deleted_at IS NULL;""")
    for n, l in enumerate(mod.LESSONS, start=1):
        qs = [dict(q=a, options=b, correct=cidx) for a, b, cidx in l["quiz"]]
        for item in qs:
            assert 0 <= item["correct"] < len(item["options"]), (l["title"], item["q"])
            assert len(item["options"]) >= 2
        ex = f"{q(l['existing_title'])}" if l.get("existing_title") else "NULL"
        out.append(f"""SELECT pg_temp.seed_lesson((SELECT id FROM courses WHERE title={q(c['title'])} AND deleted_at IS NULL LIMIT 1), {ex}, {q(l['title'])}, {q(l['content'].strip())}, {q(l.get('video',''))}, {n}, {q(json.dumps(qs))}::jsonb);""")

for term, definition in glossary.TERMS.items():
    out.append(f"INSERT INTO glossary_terms (term, definition, created_at, updated_at) VALUES ({q(term)}, {q(definition)}, now(), now()) ON CONFLICT (term) DO UPDATE SET definition=EXCLUDED.definition, deleted_at=NULL, updated_at=now();")
out.append("UPDATE glossary_terms SET deleted_at = now() WHERE term IN ('Stock','Price-to-Earnings Ratio (P/E)') AND deleted_at IS NULL;")
out.append("COMMIT;")
open("003_education.sql", "w").write("\n".join(out) + "\n")
nl = sum(len(m.LESSONS) for m in courses); nq = sum(len(l['quiz']) for m in courses for l in m.LESSONS)
print(f"{len(courses)} courses, {nl} lessons, {nq} questions, {len(glossary.TERMS)} glossary terms")
